"""T5.2 — Generate the corpus-coverage LaTeX tables for the paper.

Reads ``experiments/corpus_manifest.csv`` (written by
``experiments/corpus_run.py run``) and emits
``docs/paper/corpus_tables.tex`` containing:

* three macros (``\\corpusFilings``, ``\\corpusCompanies``,
  ``\\corpusCoverage``) so the methodology paragraph never hand-types a
  number, and
* two booktabs tables: coverage per core metric (with the dominant
  null reason) and coverage per SIC-division sector.

Every figure in the .tex is computed from the manifest — nothing is
hand-typed, matching the convention of ``experiments/make_figures.py``
(which generates ``results.tex`` the same way).

Usage
-----
::

    /home/<user>/luca-ai-lab/venv/bin/python experiments/make_corpus_tables.py
"""

from __future__ import annotations

import csv
import sys
from collections import Counter
from pathlib import Path
from typing import Final

_PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(_PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(_PROJECT_ROOT))

from experiments.corpus_run import (  # noqa: E402
    CORE_METRICS,
    MANIFEST_PATH,
    TICKERS_PATH,
)

OUTPUT_PATH: Final[Path] = _PROJECT_ROOT / "docs" / "paper" / "corpus_tables.tex"
MACROS_PATH: Final[Path] = _PROJECT_ROOT / "docs" / "paper" / "corpus_macros.tex"

#: Metric labels in the paper's Spanish table style (see results.tex).
METRIC_LABELS_ES: Final[dict[str, str]] = {
    "revenue": "Ingresos",
    "net_income": "Bº neto",
    "operating_income": "Bº op.",
    "total_assets": "Activos tot.",
    "total_equity": "Patrim. neto",
    "eps_diluted": "BPA diluido",
}

#: SIC-division sector names (manifest, English) → paper Spanish labels.
SECTOR_LABELS_ES: Final[dict[str, str]] = {
    "Agriculture": "Agricultura",
    "Mining & Energy Extraction": "Minería y extracción de energía",
    "Construction": "Construcción",
    "Manufacturing": "Manufactura",
    "Transportation, Communications & Utilities":
        "Transporte, comunicaciones y \\textit{utilities}",
    "Wholesale Trade": "Comercio mayorista",
    "Retail Trade": "Comercio minorista",
    "Finance, Insurance & Real Estate": "Finanzas, seguros e inmobiliario",
    "Services": "Servicios",
    "Other": "Otros",
    "Unknown": "Desconocido",
}

#: Null-reason vocabulary → paper Spanish labels.
REASON_LABELS_ES: Final[dict[str, str]] = {
    "tag_absent": "tag ausente",
    "not_applicable_convention": "no aplicable (convención)",
    "error": "error",
    "n/a": "--",
}


def main() -> int:
    with MANIFEST_PATH.open(encoding="utf-8", newline="") as fh:
        rows = list(csv.DictReader(fh))
    tickers = [
        line.strip()
        for line in TICKERS_PATH.read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]

    n_filings = len(rows)
    n_companies = len(tickers)
    total_cells = n_filings * len(CORE_METRICS)
    filled = sum(1 for r in rows for m in CORE_METRICS if r[m] != "NULL")
    coverage_pct = 100.0 * filled / total_cells if total_cells else 0.0

    macro_lines = [
        "% AUTO-GENERATED by experiments/make_corpus_tables.py — do not edit by hand.",
        f"% Source: {MANIFEST_PATH.name} ({n_filings} rows, {n_companies} companies).",
        "% Input this file in the preamble; corpus_tables.tex goes in the appendix.",
        f"\\newcommand{{\\corpusFilings}}{{{n_filings}}}",
        f"\\newcommand{{\\corpusCompanies}}{{{n_companies}}}",
        f"\\newcommand{{\\corpusCoverage}}{{{coverage_pct:.1f}}}",
    ]
    MACROS_PATH.write_text("\n".join(macro_lines) + "\n", encoding="utf-8")

    lines = [
        "% AUTO-GENERATED by experiments/make_corpus_tables.py — do not edit by hand.",
        f"% Source: {MANIFEST_PATH.name} ({n_filings} rows, {n_companies} companies).",
        "",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Cobertura de campos del corpus S\\&P~100 por métrica"
        f" ({n_filings} filings 10-K, {n_companies} empresas, FY2022--FY2024)."
        " Cobertura, no accuracy: la accuracy se mide solo contra el gold"
        " standard $N=60$.}",
        "\\label{tab:corpus-metric}",
        "\\begin{tabular}{lrl}",
        "\\toprule",
        "Métrica & Cobertura & Motivo dominante de null \\\\",
        "\\midrule",
    ]
    for metric in CORE_METRICS:
        got = sum(1 for r in rows if r[metric] != "NULL")
        pct = 100.0 * got / n_filings if n_filings else 0.0
        reasons = Counter(
            r[f"{metric}_null_reason"] for r in rows if r[metric] == "NULL"
        )
        dominant = reasons.most_common(1)[0][0] if reasons else "n/a"
        label = METRIC_LABELS_ES[metric]
        reason_label = REASON_LABELS_ES.get(dominant, dominant)
        lines.append(f"{label} & {pct:.1f}\\% & {reason_label} \\\\")
    lines += [
        "\\midrule",
        f"\\textbf{{Global}} & \\textbf{{{coverage_pct:.1f}\\%}} & \\\\",
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
        "",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Cobertura de campos del corpus por sector (división SIC).}",
        "\\label{tab:corpus-sector}",
        "\\begin{tabular}{lrr}",
        "\\toprule",
        "Sector & Filings & Cobertura \\\\",
        "\\midrule",
    ]
    for sector in sorted({r["sector"] for r in rows}):
        sector_rows = [r for r in rows if r["sector"] == sector]
        got = sum(1 for r in sector_rows for m in CORE_METRICS if r[m] != "NULL")
        total = len(sector_rows) * len(CORE_METRICS)
        pct = 100.0 * got / total if total else 0.0
        label = SECTOR_LABELS_ES.get(sector, sector)
        lines.append(f"{label} & {len(sector_rows)} & {pct:.1f}\\% \\\\")
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
    ]

    OUTPUT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(
        f"corpus_tables.tex: {n_filings} filings, {n_companies} empresas, "
        f"cobertura {coverage_pct:.1f}%"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
